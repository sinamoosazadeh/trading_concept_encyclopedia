#!/usr/bin/env python3
"""Rebuild or verify numbered entry blocks extracted from the preserved source."""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
SOURCE_MANIFEST_PATH = ROOT / "legacy" / "source" / "source_manifest.json"
INVENTORY_MANIFEST_PATH = ROOT / "legacy" / "catalog" / "inventory_manifest.json"
DEFAULT_OUTPUT = ROOT / "legacy" / "catalog" / "legacy_entry_inventory.jsonl"
NUMBERED_ENTRY = re.compile(r"^###\s+\d+\s*[.)]")
ANY_LEVEL_THREE = re.compile(r"^###\s+")


def read_json(path: Path) -> dict[str, Any]:
    value = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(value, dict):
        raise ValueError(f"Expected JSON object in {path}")
    return value


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def build_entries(source_text: str) -> list[dict[str, Any]]:
    """Mirror the legacy extraction algorithm, including its Unicode digit semantics."""
    lines = source_text.splitlines()
    section = "بدون بخش"
    current: dict[str, Any] | None = None
    entries: list[dict[str, Any]] = []

    def finish_current() -> None:
        nonlocal current
        if current is None:
            return
        current["content"] = "\n".join(current.pop("_lines")).rstrip()
        entries.append(current)
        current = None

    for line_number, line in enumerate(lines, start=1):
        if line.startswith("## "):
            section = line[3:].strip()
        if NUMBERED_ENTRY.match(line):
            finish_current()
            current = {
                "legacy_id": f"LEG-{len(entries) + 1:04d}",
                "section": section,
                "heading": line[4:].strip(),
                "start_line": line_number,
                "_lines": [line],
            }
        elif current is not None:
            if line.startswith("## ") or ANY_LEVEL_THREE.match(line):
                finish_current()
            else:
                current["_lines"].append(line)

    finish_current()
    return entries


def serialize_entries(entries: list[dict[str, Any]]) -> bytes:
    """Serialize using the audited JSONL formatting and stable field order."""
    text = "\n".join(json.dumps(entry, ensure_ascii=False) for entry in entries) + "\n"
    return text.encode("utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="Verify the checked-in inventory without changing files.")
    mode.add_argument("--write", action="store_true", help="Regenerate the checked-in inventory after integrity checks.")
    parser.add_argument("--root", type=Path, default=ROOT, help="Repository root (default: project root)")
    args = parser.parse_args()

    root = args.root.resolve()
    source_manifest_path = root / "legacy" / "source" / "source_manifest.json"
    inventory_manifest_path = root / "legacy" / "catalog" / "inventory_manifest.json"
    output_path = root / "legacy" / "catalog" / "legacy_entry_inventory.jsonl"

    try:
        source_manifest = read_json(source_manifest_path)
        inventory_manifest = read_json(inventory_manifest_path)
        source_path = root / str(source_manifest["repository_path"])
        source_bytes = source_path.read_bytes()
        source_digest = sha256(source_bytes)
        if source_digest != source_manifest.get("sha256"):
            raise ValueError(f"Source digest mismatch: expected {source_manifest.get('sha256')}, got {source_digest}")
        if source_manifest.get("sha256") != inventory_manifest.get("source_sha256"):
            raise ValueError("Inventory manifest references a different original-source digest.")

        source_text = source_bytes.decode("utf-8")
        entries = build_entries(source_text)
        if len(entries) != inventory_manifest.get("record_count"):
            raise ValueError(f"Entry count mismatch: expected {inventory_manifest.get('record_count')}, got {len(entries)}")

        generated = serialize_entries(entries)
        generated_digest = sha256(generated)
        if len(generated) != inventory_manifest.get("byte_length"):
            raise ValueError(f"Generated byte length mismatch: expected {inventory_manifest.get('byte_length')}, got {len(generated)}")
        if generated_digest != inventory_manifest.get("sha256"):
            raise ValueError(f"Generated inventory digest mismatch: expected {inventory_manifest.get('sha256')}, got {generated_digest}")
    except (OSError, UnicodeDecodeError, json.JSONDecodeError, KeyError, TypeError, ValueError) as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1

    if args.write:
        try:
            output_path.parent.mkdir(parents=True, exist_ok=True)
            output_path.write_bytes(generated)
        except OSError as exc:
            print(f"ERROR: cannot write {output_path}: {exc}", file=sys.stderr)
            return 1
        print(f"Wrote {len(entries)} legacy entries to {output_path.relative_to(root).as_posix()}.")
        return 0

    try:
        checked_in = output_path.read_bytes()
    except OSError as exc:
        print(f"ERROR: cannot read checked-in inventory {output_path}: {exc}", file=sys.stderr)
        print("Run with --write only after reviewing the source and inventory manifests.", file=sys.stderr)
        return 1
    if checked_in != generated:
        print("ERROR: checked-in legacy inventory differs from deterministic extraction.", file=sys.stderr)
        print("Review source changes, then use --write and update the manifest deliberately.", file=sys.stderr)
        return 1

    print("Legacy inventory verification PASSED.")
    print(json.dumps({
        "record_count": len(entries),
        "source_sha256": source_digest,
        "inventory_sha256": generated_digest,
        "byte_length": len(generated),
    }, ensure_ascii=False, indent=2, sort_keys=True))
    print("Note: this verifies extraction fidelity, not editorial quality or the truth of source claims.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
